package _02_Operators;

public class _04_RelationalOperators {
	public static void main(String[] args) {
		
//	4. Relational Operators.(Comparison) [==, !, >, <, >=, <=]
		
		int a = 20;
		int b = 15;
		int c = 10;
		
		System.out.println("a>b = " + (a>b));
		System.out.println("a<b = " + (a<b));
		System.out.println("a>=b = " + (a>b));
		System.out.println("a<=c = " + (a<=c));
		System.out.println("a==b = " + (a==b));
		System.out.println("a==c = " + (a==c));
		System.out.println("a!=b = " + (a!=b));
	}
}
